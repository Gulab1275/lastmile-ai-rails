"""
Mock Raast Instant Payment Service.
Simulates Pakistan's State Bank of Pakistan (SBP) Raast Fast Payment System.
Supports:
- Gated approval token check (Security requirement: high-risk payouts require cryptographic approval)
- Idempotency key handling (prevents double disbursement)
- Daily disbursement limits
- Chaos modes (timeout, 500, slow)
"""
import uuid
from datetime import datetime
from typing import Any, Dict, Optional

from fastapi import HTTPException

from mock.chaos import apply_chaos
from services.shared.schemas import MockRaastRequest, MockRaastResponse

# In-memory store for idempotency tracking
_PROCESSED_IDEMPOTENCY_KEYS: Dict[str, MockRaastResponse] = {}

# In-memory store for settled disbursements
_SETTLED_DISBURSEMENTS: Dict[str, Dict[str, Any]] = {}

MAX_RAAST_SINGLE_DISBURSEMENT = 25000.0


async def disburse_raast(
    req: MockRaastRequest,
    chaos_mode: Optional[str] = None
) -> MockRaastResponse:
    """
    Executes mock disbursement via Raast instant payment rail.
    """
    await apply_chaos(chaos_mode)

    # 1. Idempotency Check
    if req.idempotency_key in _PROCESSED_IDEMPOTENCY_KEYS:
        # Return exact previous response (standard idempotent payment behavior)
        return _PROCESSED_IDEMPOTENCY_KEYS[req.idempotency_key]

    # 2. Gated Approval Token Check
    # High-risk financial operations must have a valid approval token generated by Decision Engine or Human Officer
    if not req.approval_token or len(req.approval_token) < 16:
        raise HTTPException(
            status_code=403,
            detail={
                "code": "GATED_DISBURSEMENT_UNAUTHORIZED",
                "message_en": "Raast disbursement rejected: Missing or invalid cryptographic approval token.",
                "message_ur": "ادائیگی روک دی گئی: مجاز افسر یا سسٹم کی منظوری کا ٹوکن موجود نہیں ہے۔"
            }
        )

    # 3. Limit Check
    if req.amount > MAX_RAAST_SINGLE_DISBURSEMENT:
        raise HTTPException(
            status_code=400,
            detail={
                "code": "RAAST_LIMIT_EXCEEDED",
                "message_en": f"Disbursement amount {req.amount} exceeds single relief transaction limit ({MAX_RAAST_SINGLE_DISBURSEMENT}).",
                "message_ur": f"رقم کی حد تجاوز کر گئی۔ زیادہ سے زیادہ حد {MAX_RAAST_SINGLE_DISBURSEMENT} روپے ہے۔"
            }
        )

    # 4. Generate Raast Transaction Receipt
    tx_id = f"RAAST-PK-{datetime.utcnow().strftime('%Y%m%d')}-{uuid.uuid4().hex[:8].upper()}"
    resp = MockRaastResponse(
        success=True,
        transaction_id=tx_id,
        idempotency_key=req.idempotency_key,
        disbursed_amount=req.amount,
        settled_at=datetime.utcnow(),
        status="SETTLED",
        latency_ms=250
    )

    # Store for idempotency
    _PROCESSED_IDEMPOTENCY_KEYS[req.idempotency_key] = resp
    _SETTLED_DISBURSEMENTS[tx_id] = {
        "case_id": req.case_id,
        "receiver": req.receiver_iban_or_raast_id,
        "amount": req.amount,
        "settled_at": resp.settled_at
    }

    return resp

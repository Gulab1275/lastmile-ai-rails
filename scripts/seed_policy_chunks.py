def seed_policy_chunks():
    print("=" * 60)
    print("SEEDING POLICY CHUNKS INTO SUPABASE PGVECTOR...")
    print("=" * 60)

    with engine.connect() as conn:
        # Check if table exists
        conn.execute(text("CREATE EXTENSION IF NOT EXISTS vector;"))
        conn.execute(text("""
            CREATE TABLE IF NOT EXISTS policy_chunks (
                id VARCHAR PRIMARY KEY,
                document_name VARCHAR NOT NULL,
                page_number INTEGER NOT NULL,
                content TEXT NOT NULL,
                embedding_json JSON,
                embedding vector(384),
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
        """))
        conn.commit()

        # Clear existing rows for clean seed
        conn.execute(text("DELETE FROM policy_chunks;"))
        conn.commit()

        total = len(POLICY_CORPUS)
        for i, chunk in enumerate(POLICY_CORPUS, start=1):
            doc_id = str(uuid.uuid4())
            emb = generate_embedding(chunk["content"])
            emb_str = "[" + ",".join(str(x) for x in emb) + "]"

            conn.execute(
                text("""
                    INSERT INTO policy_chunks (id, document_name, page_number, content, embedding_json, embedding)
                    VALUES (:id, :document_name, :page_number, :content, CAST(:embedding_json AS json), CAST(:embedding AS vector));
                """),
                {
                    "id": doc_id,
                    "document_name": chunk["document_name"],
                    "page_number": chunk["page_number"],
                    "content": chunk["content"],
                    "embedding_json": str(emb).replace("'", '"'),
                    "embedding": emb_str
                }
            )
            print(f"[{i:02d}/{total:02d}] Seeded '{chunk['document_name'][:30]}...' (Page {chunk['page_number']})")

        conn.commit()

        # Verify count
        count = conn.execute(text("SELECT count(*) FROM policy_chunks;")).scalar()
        print(f"\n[SUCCESS] Successfully seeded {count} policy chunks into Supabase pgvector!")

        # Test pgvector query
        test_q = "What is the monthly income limit for widow assistance?"
        q_emb = generate_embedding(test_q)
        q_emb_str = "[" + ",".join(str(x) for x in q_emb) + "]"

        res = conn.execute(
            text("""
                SELECT document_name, page_number, content, 1 - (embedding <=> CAST(:q_emb AS vector)) AS similarity
                FROM policy_chunks
                ORDER BY embedding <=> CAST(:q_emb AS vector) ASC
                LIMIT 2;
            """),
            {"q_emb": q_emb_str}
        ).fetchall()

        print("\nTest pgvector Top Match:")
        for r in res:
            print(f"  -> Doc: {r[0]} (Page {r[1]}) | Similarity: {round(float(r[3]), 4)}")
            print(f"     Excerpt: {r[2][:90]}...")

if __name__ == "__main__":
    seed_policy_chunks()

"""
Mock External DPI Rails API Endpoints.
Simulates Pakistan's public rails:
1. NADRA Identity Verification with fuzzy matching & chaos mode
2. Raast Instant Payments with gated cryptographic authorization token & chaos mode
3. Citizen Grievances / Complaints Redressal with chaos mode
"""
from typing import Optional

from fastapi import APIRouter, Query

from mock.complaints import lodge_complaint
from mock.nadra import verify_identity_nadra
from mock.raast import disburse_raast
from services.api.engine.audit_log import audit_log
from services.shared.schemas import (
    MockComplaintRequest,
    MockComplaintResponse,
    MockNADRARequest,
    MockNADRAResponse,
    MockRaastRequest,
    MockRaastResponse,
)

router = APIRouter(prefix="/mock", tags=["Mock Public Rails (DPI)"])


@router.post("/identity/verify", response_model=MockNADRAResponse)
async def mock_nadra_verify(
    req: MockNADRARequest,
    chaos: Optional[str] = Query(None, description="Chaos mode: timeout, 500, slow, none")
):
    """
    Simulates NADRA Citizen Identity Verification.
    Matches CNIC and performs fuzzy name transliteration.
    Supports ?chaos=timeout|500|slow.
    """
    resp = await verify_identity_nadra(req, chaos_mode=chaos)

    audit_log.append(
        actor_id="system_mock_nadra",
        actor_role="admin",
        action="NADRA_IDENTITY_VERIFIED",
        resource_id=resp.canonical_cnic,
        details={"matched": resp.matched, "score": resp.match_score, "chaos": chaos}
    )

    return resp


@router.post("/payment/disburse", response_model=MockRaastResponse)
async def mock_raast_disburse(
    req: MockRaastRequest,
    chaos: Optional[str] = Query(None, description="Chaos mode: timeout, 500, slow, none")
):
    """
    Simulates SBP Raast Fast Payment Rail.
    CRITICAL SECURITY CHECK: Requires a valid cryptographic approval token
    generated by the Decision Engine or an Officer review.
    Supports idempotency keys to prevent duplicate disbursement.
    """
    resp = await disburse_raast(req, chaos_mode=chaos)

    audit_log.append(
        actor_id="system_mock_raast",
        actor_role="admin",
        action="RAAST_DISBURSEMENT_SETTLED",
        resource_id=req.case_id,
        details={
            "tx_id": resp.transaction_id,
            "amount": req.amount,
            "idempotency_key": req.idempotency_key
        }
    )

    return resp


@router.post("/complaints", response_model=MockComplaintResponse)
async def mock_lodge_complaint(
    req: MockComplaintRequest,
    chaos: Optional[str] = Query(None, description="Chaos mode: timeout, 500, slow, none")
):
    """
    Simulates Citizen Grievance Redressal / Complaint Portal.
    """
    resp = await lodge_complaint(req, chaos_mode=chaos)

    audit_log.append(
        actor_id=req.citizen_cnic,
        actor_role="citizen",
        action="COMPLAINT_LODGED",
        resource_id=resp.ticket_id,
        details={"category": req.category, "queue": resp.assigned_queue}
    )

    return resp
